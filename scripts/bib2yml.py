#!/usr/bin/env python3
"""Turn the CV's BibTeX file into _data/publications.yml for the website.

Usage (from the repository root):

    python3 scripts/bib2yml.py path/to/CV/publications/pubs.bib

No dependencies beyond the standard library. The parser is deliberately small:
it handles the conventions used in fcmocanu/CV (\\textbf{...} around my name,
\\ce{...} chemistry, \\textit{...}, braces for capitalisation).
Topics are guessed from the title; override them in TOPIC_OVERRIDES.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "_data" / "publications.yml"

# First match wins, case-insensitive.
TOPIC_RULES = [
    ("phase-change", r"Ge2Sb2Te5|Sb2Te3|phase-change"),
    ("energy", r"cathode|batter|electrolyte|LiF|PO4|perovskite|electrochemical"),
    ("glasses", r"glass|two-level|non-phononic|heterogeneous-elasticity|sorbitol|amorphous"),
    ("devices", r"quantum dot|transistor|strain sensor"),
]
TOPIC_OVERRIDES = {}  # e.g. {"arber_ion_2025": "energy"}


def parse_bib(text):
    entries = []
    for m in re.finditer(r"@(\w+)\{([^,]+),(.*?)\n\}", text, re.S):
        kind, key, body = m.groups()
        fields = {}
        for line in body.splitlines():
            line = line.strip()
            if line.startswith("%"):
                continue
            fm = re.match(r"(\w+)\s*=\s*(.*?),?$", line)
            if not fm:
                continue
            name, val = fm.groups()
            val = val.strip()
            if val.startswith("{") and val.endswith("}"):
                val = val[1:-1]
            fields[name.lower()] = val
        entries.append((kind, key.strip(), fields))
    return entries


def ce(formula):
    # \ce{Ge2Sb2Te5} -> Ge<sub>2</sub>Sb<sub>2</sub>Te<sub>5</sub>
    return re.sub(r"(?<=[A-Za-z\)])(\d+)", r"<sub>\1</sub>", formula)


def latex_to_html(s):
    s = re.sub(r"\\ce\{([^{}]*)\}", lambda m: ce(m.group(1)), s)
    s = re.sub(r"\{\\textsc\{([^{}]*)\}\}", r"\1", s)
    s = re.sub(r"\\textsc\{([^{}]*)\}", r"\1", s)
    s = re.sub(r"\\textit\{([^{}]*)\}", r"<i>\1</i>", s)
    s = s.replace("--", "–").replace("\\&", "&")
    s = re.sub(r"[{}]", "", s)
    return s


def authors(s):
    out = []
    for a in s.split(" and "):
        me = "\\textbf" in a
        a = re.sub(r"\\textbf\{([^{}]*)\}", r"\1", a)
        a = latex_to_html(a).strip()
        if "," in a:
            last, first = [p.strip() for p in a.split(",", 1)]
            initials = " ".join(p[0] + "." for p in re.split(r"[\s.]+", first) if p)
            a = f"{initials} {last}"
        out.append(f"<strong>{a}</strong>" if me else a)
    return ", ".join(out)


def topic(key, title):
    if key in TOPIC_OVERRIDES:
        return TOPIC_OVERRIDES[key]
    for name, rx in TOPIC_RULES:
        if re.search(rx, title, re.I):
            return name
    return "other"


def yq(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(bib):
    entries = parse_bib(Path(bib).read_text(encoding="utf-8"))
    rows = []
    for kind, key, f in entries:
        kw = f.get("keywords", "")
        rows.append({
            "key": key,
            "title": latex_to_html(f.get("title", "")),
            "authors": authors(f.get("author", "")),
            "journal": latex_to_html(f.get("journal", f.get("journaltitle", ""))),
            "volume": f.get("volume", ""),
            "pages": latex_to_html(f.get("pages", "")),
            "year": f.get("year", f.get("date", "")[:4]),
            "doi": f.get("doi", ""),
            "status": "preprint" if ("submitted" in kw or "preprint" in kw) else "published",
            "topic": topic(key, f.get("title", "")),
            "first_author": f.get("author", "").lstrip().startswith("\\textbf"),
        })
    rows.sort(key=lambda r: r["year"], reverse=True)  # stable: keeps bib order within a year
    lines = ["# Generated by scripts/bib2yml.py from fcmocanu/CV publications/pubs.bib. Do not edit by hand."]
    for r in rows:
        lines.append(f"- key: {r['key']}")
        for k in ("title", "authors", "journal", "volume", "pages", "year", "doi", "status", "topic"):
            lines.append(f"  {k}: {yq(str(r[k]))}")
        lines.append(f"  first_author: {'true' if r['first_author'] else 'false'}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} entries to {OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../CV/publications/pubs.bib")
